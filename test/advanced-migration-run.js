(async () => {
  const result = document.querySelector("#harness-result");
  const wait = () => new Promise((resolve) => migrationNativeTimeout(resolve, 0));
  const settle = async () => { await wait(); await wait(); };
  const $ = (selector) => document.querySelector(selector);
  const assert = (condition, text) => { if (!condition) throw new Error(text); };
  const click = (selector) => { assert($(selector), `Missing ${selector}`); $(selector).click(); };
  const set = (selector, value, event = "input") => { $(selector).value = value; $(selector).dispatchEvent(new Event(event)); };
  const changes = () => popupHarnessState.commands.filter((command) => command.kind === "workspaceCommand");
  const reads = () => popupHarnessState.commands.filter((command) => command.payload?.kind === "readValues");
  const showCandidates = () => popupHarnessState.emitPagePayload({ kind: "scanResults", requestId: "quick:migration", instanceId: "memory-1", type: "i32", multiplier: 1, total: 1000,
    preview: [{ address: 16, type: "i32", value: 5 }, { address: 32, type: "i32", value: 15 }, { address: 48, type: "i32", value: 10 }], allCandidates: false,
  });
  try {
    await settle();
    click('[data-view="advanced"]');
    click('[data-workspace="watches"]');
    assert(!$("#open-inspector"), "Legacy inspector launcher remains");
    set("#manual-type", "i32", "change");
    set("#manual-multiplier", "4");
    for (const invalid of ["12junk", "0x10oops", "1e3", "-1", "1.5", "", "999999999999999999999", "4718591"]) {
      const before = changes().length;
      set("#manual-address", invalid);
      click("#manual-add");
      await settle();
      assert(changes().length === before, `Invalid address accepted: ${invalid}`);
      assert($("#manual-status").textContent.trim(), `Invalid address lacks feedback: ${invalid}`);
    }
    migrationState.holdReads = true;
    set("#manual-address", "0x100");
    const beforeManual = changes().length;
    click("#manual-add");
    await settle();
    assert(reads().at(-1)?.payload.entries.some((entry) => entry.address === 256 && entry.type === "i32"), "Manual address was not read with explicit type");
    assert(changes().length === beforeManual, "Manual address added before successful read");
    migrationState.holdReads = false;
    migrationState.heldReads.splice(0).forEach((respond) => respond());
    await settle();
    assert(migrationState.watches.length === 1 && migrationState.watches[0].address === 256 && migrationState.watches[0].multiplier === 4, "Valid hex address was not added with multiplier");
    assert(!popupHarnessState.commands.some((command) => ["writeValue", "setFreeze"].includes(command.payload?.kind)), "Manual add wrote or froze memory");
    migrationState.watches[0].label = "Health";
    migrationState.watches[0].group = "Player";
    publishMigrationWorkspace();
    set("#manual-address", "256");
    click("#manual-add");
    await settle();
    assert(migrationState.watches.length === 1 && migrationState.watches[0].label === "Health" && migrationState.watches[0].group === "Player", "Duplicate address lost metadata");
    migrationState.failReads = true;
    set("#manual-address", "512");
    click("#manual-add");
    await settle();
    assert(migrationState.watches.length === 1, "Failed manual read added a watch");
    migrationState.failReads = false;

    click('[data-workspace="candidates"]');
    showCandidates();
    await settle();
    assert($("#advanced-preview-count").textContent.includes("3"), "Preview size not shown separately");
    const beforeSelection = changes().length;
    click("#candidate-select-mode");
    click("#candidate-select-visible");
    assert(document.querySelectorAll('#advanced-candidates input[data-batch-key]:checked').length === 3, "Select visible did not select preview rows");
    assert(changes().length === beforeSelection, "Selection unexpectedly changed watches");
    set("#advanced-filter", "missing");
    set("#advanced-filter", "");
    assert(document.querySelectorAll('#advanced-candidates input[data-batch-key]:checked').length === 0, "Filtered hidden rows retained selection");
    click("#candidate-select-visible");
    click("#batch-watch");
    await settle();
    assert(migrationState.watches.length === 4, "Watch selected did not add selected preview");
    click('[data-workspace="watches"]');
    click("#watch-select-mode");
    click("#watch-select-visible");
    set("#batch-label", "");
    set("#batch-group", "Tracked");
    click("#batch-metadata");
    await settle();
    assert(migrationState.watches.every((watch) => watch.group === "Tracked"), "Batch group not applied");
    assert(migrationState.watches.find((watch) => watch.address === 256).label === "Health", "Blank batch label erased metadata");
    const key = migrationKey(migrationState.watches[0]);
    for (const [state, expected] of [["checking", "Checking"], ["verified", "250 ms"], ["restored", "Game restored"], ["rejected", "rejected"], ["unavailable", "Unavailable"]]) {
      migrationState.diagnostics = { [key]: { requestId: "quick:write-test", state, detail: `Timing detail ${state}` } };
      publishMigrationWorkspace();
      assert($(".watch-state")?.textContent.includes(expected), `Incorrect ${state} diagnostic status`);
      assert(document.body.textContent.includes(`Timing detail ${state}`), `Missing ${state} timing details`);
    }
    const detail = document.querySelector(`[data-watch-key="${key}"]`);
    detail.open = true;
    const draft = $("[aria-label^='Watch label']");
    draft.focus(); draft.value = "Unsaved draft";
    publishMigrationWorkspace();
    assert(document.querySelector(`[data-watch-key="${key}"]`).open, "Workspace refresh collapsed diagnostic details");
    assert(document.activeElement === $("[aria-label^='Watch label']") && document.activeElement.value === "Unsaved draft", "Workspace refresh lost focused metadata draft");
    document.activeElement.blur();
    migrationState.frozenKeys = [key];
    publishMigrationWorkspace();
    assert([...document.querySelectorAll(".watch-state")].some((node) => /frozen/i.test(node.textContent)), "Frozen watch status missing");
    migrationState.frozenKeys = [];
    migrationState.failReads = true;
    publishMigrationWorkspace();
    await settle();
    assert(!$(".watch-row .candidate-value") || /—|unavailable|\?/i.test($(".watch-row .candidate-value").textContent), "Failed read left stale live value");
    migrationState.failReads = false;
    migrationState.diagnostics = {};
    publishMigrationWorkspace();
    await settle();
    assert($(".watch-row .candidate-value").textContent !== "—", "Successful subsequent read did not recover value");
    assert($(".watch-state").textContent === "Live", "Read recovery retained unavailable status");
    migrationState.diagnostics = { [key]: { requestId: "quick:final", state: "verified", detail: "Complete 250 ms check" } };
    migrationState.selectedKey = key;
    publishMigrationWorkspace();
    click('[data-view="simple"]');
    assert($("#quick-editor .selected-feedback").textContent.includes("250 ms"), "Simple selected feedback missed final diagnostic");
    click('[data-view="advanced"]');
    const beforeDisconnectReads = reads().length;
    popupHarnessState.emitMessage({ kind: "frameDisconnected", frameId: 0 });
    assert($(".watch-row .candidate-value").textContent === "—" && $(".watch-state").textContent === "Unavailable", "Disconnected frame left a live watch value");
    publishMigrationWorkspace();
    await settle();
    assert(reads().length === beforeDisconnectReads, "Polling read from a disconnected frame");
    popupHarnessState.resetInstances();
    publishMigrationWorkspace();
    await settle();
    migrationState.watches = Array.from({ length: 256 }, (_, index) => ({ frameId: 0, instanceId: "memory-1", type: "i32", multiplier: 1, address: 1024 + index * 4, label: "", group: "" }));
    publishMigrationWorkspace();
    set("#manual-address", "8192");
    click("#manual-add");
    await settle();
    assert(migrationState.watches.length === 256, "Watch capacity exceeded");
    assert(/limit|256|skip|full/i.test($("#manual-status").textContent), "Watch capacity failure lacks feedback");
    click('[data-workspace="candidates"]');
    showCandidates();
    click("#candidate-select-mode");
    click("#candidate-select-visible");
    click('[data-workspace="watches"]');
    click('[data-workspace="candidates"]');
    assert(document.querySelectorAll('[data-batch-key]:checked').length === 0, "Workspace switch retained selection");
    click("#candidate-select-mode");
    click("#candidate-select-visible");
    popupHarnessState.emitPagePayload({ kind: "scanResults", requestId: "quick:replacement", instanceId: "memory-1", type: "i32", total: 1, preview: [{ address: 64, type: "i32", value: 8 }] });
    assert(document.querySelectorAll('[data-batch-key]:checked').length === 0, "New result set retained selection");
    click("#candidate-select-mode");
    click("#candidate-select-visible");
    $("#advanced-instance").dispatchEvent(new Event("change"));
    assert(document.querySelectorAll('[data-batch-key]:checked').length === 0, "Memory switch retained selection");
    const scanning = { requestId: "quick:stalled", status: "scanning", frameId: 0, instanceId: "memory-1", canRefine: true, progress: null };
    popupHarnessState.emitMessage({ kind: "quickSession", session: scanning });
    assert(migrationState.stalledCallbacks.length > 0, "Missing 15-second stalled scan timer");
    const recoveryCount = () => popupHarnessState.commands.filter((command) => command.payload?.kind === "getSessionState").length;
    const beforeRecovery = recoveryCount();
    migrationState.stalledCallbacks.at(-1)();
    assert(/No recent progress/.test($("#advanced-status").textContent), "Stalled scan lacks progress feedback");
    assert(recoveryCount() === beforeRecovery + 1, "Stalled scan did not request authoritative state once");
    assert($("#advanced-scan").disabled && !$("#cancel-advanced-scan").hidden, "Watchdog unlocked scan or removed cancellation");
    const timerCount = migrationState.stalledCallbacks.length;
    popupHarnessState.emitMessage({ kind: "quickSession", session: { ...scanning } });
    popupHarnessState.emitPagePayload({ kind: "scanProgress", requestId: "quick:stalled", inspected: 10, total: 100 });
    assert(migrationState.stalledCallbacks.length === timerCount && recoveryCount() === beforeRecovery + 1, "Watchdog repeated recovery for same scan");
    popupHarnessState.emitPagePayload({ kind: "scanResults", requestId: "quick:stalled", instanceId: "memory-1", type: "i32", total: 1, preview: [{ address: 64, type: "i32", value: 8 }] });
    assert(!$("#advanced-scan").disabled && $("#cancel-advanced-scan").hidden, "Delayed legitimate scan completion did not recover");
    await new Promise((resolve, reject) => {
      const script = document.createElement("script"); script.src = "../workspace-controls.js";
      script.onload = resolve; script.onerror = reject; document.body.append(script);
    });
    await settle();
    const stage = (payload) => document.dispatchEvent(new CustomEvent("hack-engine-import", { detail: payload }));
    const valid = { format: "hack-engine-workspace", version: 2, name: "Current workspace", watches: [{ address: 128, type: "i32", multiplier: 4, label: "Coins", group: "Player" }], settings: { type: "f64", alignment: "byte", multiplier: 4 } };
    for (const rejected of [{ ...valid, version: 1 }, { version: 1, watches: valid.watches }, { ...valid, version: 4 }, { ...valid, watches: [{ type: "f64", address: -1 }] }]) {
      stage(rejected);
      assert($("[data-preview]").hidden && /unsupported|invalid/i.test($(".session-feedback").textContent), "Legacy or malformed workspace was accepted");
    }
    migrationState.watches = [];
    const beforeImport = changes().length;
    stage(valid);
    assert(!$("[data-preview]").hidden && $("[data-preview-values]").textContent.includes("Coins"), "Version 2 import preview missing");
    click('[data-action="apply"]');
    await settle();
    assert(changes().length === beforeImport, "Workspace applied without address verification");
    let importedSettings;
    document.addEventListener("hack-engine-settings", (event) => { importedSettings = event.detail; });
    $("[data-verified]").checked = true;
    click('[data-action="apply"]');
    await settle();
    const imported = changes().at(-1);
    assert(imported.action === "mergeWatches" && imported.watches[0].label === "Coins" && imported.watches[0].group === "Player" && imported.watches[0].multiplier === 4 && imported.watches[0].instanceId === "memory-1", "Version 2 import lost metadata or target binding");
    assert(importedSettings.type === "f64" && importedSettings.alignment === "byte" && importedSettings.multiplier === 4, "Import lost supported scan settings");
    assert(!popupHarnessState.commands.some((command) => ["writeValue", "setFreeze"].includes(command.payload?.kind)), "Import replayed a write or freeze");
    migrationState.watches = Array.from({ length: 256 }, (_, index) => ({ frameId: 0, instanceId: "memory-1", type: "i32", address: 1024 + index * 4, multiplier: 1 }));
    stage(valid); $("[data-verified]").checked = true;
    click('[data-action="apply"]');
    await settle();
    assert(!$("[data-preview]").hidden && /0 watches accepted.*1 skipped/.test($(".session-feedback").textContent), "Capacity-limited import implied success or closed preview");
    result.textContent = "PASS: Advanced manual addresses, batch boundaries, diagnostics/read recovery, capacity, stalled recovery, and version 2 import work.";
  } catch (error) {
    result.textContent = `FAIL: ${error.stack || error}`;
  }
})();
